"""Build Alice's synthetic pod on provider A, and export/import it again.

All people, addresses and notes are FICTIONAL. The structure is deliberately
realistic rather than minimal: nested containers, resources that reference each
other, a binary, and one container carrying its own ACL -- because a migration
that only moves one flat Turtle file proves nothing about migration.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from solidlib.resources import create_container, put_bytes, put_turtle, walk
from solidlib.session import SolidSession
from solidlib.wac import container_owner_only, write_acl

FIXTURES = Path(__file__).resolve().parents[2] / "fixtures"
ROOT_NAME = "thesis-lab/"


def _docs(base: str) -> dict[str, str]:
    """The Turtle documents, with cross-references expressed as absolute IRIs.

    Absolute IRIs are the interesting case: they are what breaks when data moves
    between origins, and what a relative-IRI-only dataset would hide.
    """
    root = f"{base}{ROOT_NAME}"
    return {
        f"{root}profile.ttl": f"""@prefix foaf: <http://xmlns.com/foaf/0.1/>.
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#>.
@prefix pim: <http://www.w3.org/ns/pim/space#>.

<#alice> a foaf:Person ;
    foaf:name "Alice Bergmann (synthetic test data)" ;
    rdfs:comment "Fictional person. Not a real data subject." ;
    pim:storage <{base}> ;
    foaf:knows <{root}contacts/carol.ttl#carol>, <{root}contacts/dave.ttl#dave> ;
    rdfs:seeAlso <{root}notes/note-1.ttl> .
""",
        f"{root}contacts/carol.ttl": f"""@prefix foaf: <http://xmlns.com/foaf/0.1/>.
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#>.

<#carol> a foaf:Person ;
    foaf:name "Carol Nieminen (synthetic)" ;
    foaf:mbox <mailto:carol@example.invalid> ;
    rdfs:comment "Fictional contact." ;
    foaf:knows <{root}profile.ttl#alice> .
""",
        f"{root}contacts/dave.ttl": f"""@prefix foaf: <http://xmlns.com/foaf/0.1/>.
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#>.

<#dave> a foaf:Person ;
    foaf:name "Dave Okonkwo (synthetic)" ;
    foaf:mbox <mailto:dave@example.invalid> ;
    rdfs:comment "Fictional contact." .
""",
        f"{root}notes/note-1.ttl": f"""@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#>.
@prefix dct: <http://purl.org/dc/terms/>.
@prefix foaf: <http://xmlns.com/foaf/0.1/>.

<#note> a rdfs:Resource ;
    dct:title "Meeting notes (synthetic)" ;
    dct:created "2026-03-04" ;
    dct:references <{root}contacts/carol.ttl#carol> ;
    foaf:depiction <{root}media/portrait.png> ;
    rdfs:comment "Fictional content for a migration test." .
""",
        f"{root}notes/note-2.ttl": f"""@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#>.
@prefix dct: <http://purl.org/dc/terms/>.

<#note> a rdfs:Resource ;
    dct:title "Follow-up notes (synthetic)" ;
    dct:isReferencedBy <{root}notes/note-1.ttl#note> ;
    dct:references <{root}notes/note-1.ttl#note> .
""",
        f"{root}media/portrait.ttl": f"""@prefix dct: <http://purl.org/dc/terms/>.
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#>.

<{root}media/portrait.png>
    dct:title "Generated placeholder image (depicts nobody)" ;
    dct:license <https://creativecommons.org/publicdomain/zero/1.0/> ;
    dct:creator "Generated by fixtures/generate.py" ;
    rdfs:comment "This licence statement is part of the test scenario: it is content being migrated, and whether it survives the move is observed." .
""",
    }


def containers(base: str) -> list[str]:
    root = f"{base}{ROOT_NAME}"
    return [root, f"{root}contacts/", f"{root}notes/", f"{root}media/"]


def build(session: SolidSession, base: str) -> str:
    """Create the whole fixture pod. Returns the root container URL."""
    root = f"{base}{ROOT_NAME}"
    for container in containers(base):
        create_container(session, container)
    for url, turtle in _docs(base).items():
        put_turtle(session, url, turtle)
    put_bytes(
        session,
        f"{root}media/portrait.png",
        (FIXTURES / "portrait.png").read_bytes(),
        "image/png",
    )
    # One container carries its own ACL, so the migration has something
    # non-default to lose.
    write_acl(session, root, container_owner_only(root, session.web_id or ""))
    return root


def export(session: SolidSession, root: str) -> dict[str, tuple[str, bytes]]:
    """Export everything reachable by ``ldp:contains`` traversal.

    This is what a naive "download my pod" client sees. Notably it does **not**
    include auxiliary resources such as ``.acl`` -- they are not contained
    resources, so nothing in the containment model reveals them.
    """
    out: dict[str, tuple[str, bytes]] = {}
    for url in walk(session, root):
        if url.endswith("/"):
            out[url] = ("__container__", b"")
            continue
        response = session.get(url)
        if response.ok:
            out[url] = (response.headers.get("Content-Type", "").split(";")[0], response.content)
    return out


def rewrite(data: bytes, old_base: str, new_base: str, content_type: str) -> bytes:
    """Rewrite provider-A IRIs to provider-B IRIs in textual RDF only.

    Binaries are passed through untouched -- rewriting their bytes would corrupt
    them, which is itself part of why link rewriting is not a general solution.
    """
    if content_type.startswith("image/") or content_type == "__container__":
        return data
    return data.replace(old_base.encode(), new_base.encode())


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()
